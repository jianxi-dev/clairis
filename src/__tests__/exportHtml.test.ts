import { describe, it, expect } from "vitest";
import { buildHtmlDocument, escapeHtml } from "../lib/export/html";
import { inlineImages } from "../lib/export/inlineImages";

const CSS = ".preview-content { color: red; }";

describe("buildHtmlDocument", () => {
  it("wraps rendered markdown in a full html document", () => {
    const doc = buildHtmlDocument("# 标题\n\n正文段落。", {
      title: "我的文档",
      css: CSS,
    });

    expect(doc.startsWith("<!doctype html>")).toBe(true);
    expect(doc).toContain('<html lang="zh-CN">');
    expect(doc).toContain('<meta charset="utf-8" />');
    expect(doc).toContain("<title>我的文档</title>");
    expect(doc).toContain("<h1");
    expect(doc).toContain("标题");
    expect(doc).toContain("正文段落。");
  });

  it("inlines the given css in a single style block", () => {
    const doc = buildHtmlDocument("# t", { title: "t", css: CSS });
    const styles = doc.match(/<style>/g) ?? [];
    expect(styles).toHaveLength(1);
    expect(doc).toContain(".preview-content { color: red; }");
  });

  it("escapes the title", () => {
    const doc = buildHtmlDocument("# t", {
      title: '<script>alert("x")</script> & more',
      css: CSS,
    });
    expect(doc).toContain(
      "<title>&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &amp; more</title>",
    );
    expect(doc).not.toContain("<script>alert");
  });

  it("references no external scripts or stylesheets", () => {
    const doc = buildHtmlDocument("# t\n\n[链接](https://example.com)", {
      title: "t",
      css: CSS,
    });
    expect(doc).not.toMatch(/<script[^>]+src=/i);
    expect(doc).not.toMatch(/<link[^>]+rel=["']?stylesheet/i);
    expect(doc).not.toMatch(/<script[^>]+src=["']https?:/i);
  });

  it("injects no byline or generator signature", () => {
    const doc = buildHtmlDocument("# t", { title: "t", css: CSS });
    expect(doc.toLowerCase()).not.toContain("byline");
    expect(doc.toLowerCase()).not.toContain("generated by");
    expect(doc.toLowerCase()).not.toContain("made with");
  });

  it("leaves mermaid source untouched when no renderer is injected", () => {
    const doc = buildHtmlDocument("```mermaid\ngraph TD\nA-->B\n```", {
      title: "t",
      css: CSS,
    });
    expect(doc).toContain("A--&gt;B");
    expect(doc).not.toContain("<svg");
  });

  it("replaces the mermaid source with the injected SVG", () => {
    const seen: string[] = [];
    const doc = buildHtmlDocument('```mermaid\ngraph TD\nA-->B & "x"\n```', {
      title: "t",
      css: CSS,
      diagramSvg: (source) => {
        seen.push(source);
        return '<svg class="exported-diagram"></svg>';
      },
    });

    expect(doc).toContain('<svg class="exported-diagram">');
    expect(doc).not.toContain("A--&gt;B");
    expect(doc).not.toContain("flowchart");
    expect(seen).toEqual(['graph TD\nA-->B & "x"']);
  });

  it("keeps the source block when the injected renderer returns null", () => {
    const doc = buildHtmlDocument("```mermaid\ngraph TD\nA-->B\n```", {
      title: "t",
      css: CSS,
      diagramSvg: () => null,
    });
    expect(doc).toContain("A--&gt;B");
    expect(doc).not.toContain("<svg");
  });
});

describe("escapeHtml", () => {
  it("escapes the five html special characters", () => {
    expect(escapeHtml(`<a href="x">&'</a>`)).toBe(
      "&lt;a href=&quot;x&quot;&gt;&amp;&#39;&lt;/a&gt;",
    );
  });
});

describe("inlineImages", () => {
  const readOk = async (path: string) =>
    path === "/docs/pic.png" ? "QUJD" : null;

  it("rewrites relative image src to a data url", async () => {
    const html = '<p><img src="pic.png" alt="图" /></p>';
    const result = await inlineImages(html, "/docs", readOk);

    expect(result.inlined).toBe(1);
    expect(result.failed).toBe(0);
    expect(result.html).toContain('src="data:image/png;base64,QUJD"');
    expect(result.html).toContain('alt="图"');
  });

  it("keeps the original src and counts failures when the file is unreadable", async () => {
    const html = '<img src="missing.jpg" alt="x" />';
    const result = await inlineImages(html, "/docs", readOk);

    expect(result.inlined).toBe(0);
    expect(result.failed).toBe(1);
    expect(result.html).toContain('src="missing.jpg"');
  });

  it("leaves remote, data and absolute urls untouched", async () => {
    const html = [
      '<img src="https://example.com/a.png" />',
      '<img src="data:image/png;base64,AAAA" />',
      '<img src="/abs/b.png" />',
    ].join("");
    const result = await inlineImages(html, "/docs", readOk);

    expect(result.inlined).toBe(0);
    expect(result.failed).toBe(0);
    expect(result.html).toBe(html);
  });

  it("mixes inlined and failed images without shifting indices", async () => {
    const html =
      '<img src="pic.png" /><img src="gone.png" /><img src="pic.png" />';
    const result = await inlineImages(html, "/docs", readOk);

    expect(result.inlined).toBe(2);
    expect(result.failed).toBe(1);
    expect(result.html.match(/data:image\/png;base64,QUJD/g)).toHaveLength(2);
    expect(result.html).toContain('src="gone.png"');
  });
});
